"""Provider-agnostic LLM client using httpx."""
from __future__ import annotations

import json
from typing import Any, Dict, Optional
import httpx

from utils.config import settings
from utils.logger import get_logger

logger = get_logger(__name__)


class LLMUnavailable(Exception):
    """Raised when the LLM provider is disabled ('none'), unreachable, or fails."""
    pass


class LLMClient:
    """Provider-agnostic LLM client supporting local and remote providers."""

    def __init__(
        self,
        provider: Optional[str] = None,
        model: Optional[str] = None,
        api_key: Optional[str] = None,
        base_url: Optional[str] = None,
        timeout: Optional[float] = None,
    ):
        self.provider = (provider or getattr(settings, "llm_provider", "none") or "none").strip().lower()
        self.model = model or getattr(settings, "llm_model", None)
        self.api_key = api_key or getattr(settings, "llm_api_key", None)
        self.base_url = (base_url or getattr(settings, "llm_base_url", None) or "").rstrip("/")
        self.timeout = float(timeout or getattr(settings, "llm_timeout_seconds", 20.0))

    async def generate(
        self,
        system: str,
        user: str,
        json_schema: Optional[Dict[str, Any]] = None,
    ) -> str:
        """
        Generate text response from the configured LLM provider.

        Args:
            system: System instructions
            user: User prompt / facts data
            json_schema: Optional schema dictionary for structured output

        Returns:
            The raw string response generated by the model

        Raises:
            LLMUnavailable: If the provider is disabled, times out, or fails
        """
        if self.provider in ("none", "", None):
            logger.debug("llm_call_skipped", provider=self.provider, reason="provider_is_none")
            raise LLMUnavailable("LLM provider is set to 'none' or unconfigured")

        logger.info("llm_call_started", provider=self.provider, model=self.model or "default")

        try:
            async with httpx.AsyncClient(timeout=self.timeout) as client:
                if self.provider == "ollama":
                    return await self._call_ollama(client, system, user, json_schema)
                elif self.provider == "openai":
                    return await self._call_openai(client, system, user, json_schema)
                elif self.provider == "anthropic":
                    return await self._call_anthropic(client, system, user, json_schema)
                elif self.provider == "gemini":
                    return await self._call_gemini(client, system, user, json_schema)
                else:
                    raise LLMUnavailable(f"Unsupported LLM provider: {self.provider}")
        except httpx.TimeoutException as exc:
            logger.warning("llm_call_timeout", provider=self.provider, timeout=self.timeout)
            raise LLMUnavailable(f"LLM request timed out after {self.timeout}s: {exc}") from exc
        except httpx.HTTPStatusError as exc:
            # Avoid logging sensitive response headers/keys
            status = exc.response.status_code if exc.response is not None else "unknown"
            logger.warning("llm_call_http_error", provider=self.provider, status_code=status)
            raise LLMUnavailable(f"LLM provider returned HTTP {status}") from exc
        except LLMUnavailable:
            raise
        except Exception as exc:
            logger.warning("llm_call_failed", provider=self.provider, error=str(exc)[:150])
            raise LLMUnavailable(f"LLM provider execution error: {str(exc)[:150]}") from exc

    async def _call_ollama(
        self,
        client: httpx.AsyncClient,
        system: str,
        user: str,
        json_schema: Optional[Dict[str, Any]],
    ) -> str:
        base = self.base_url or "http://localhost:11434"
        url = f"{base}/api/chat"
        payload: Dict[str, Any] = {
            "model": self.model or "llama3",
            "messages": [
                {"role": "system", "content": system},
                {"role": "user", "content": user},
            ],
            "stream": False,
        }
        if json_schema is not None:
            payload["format"] = "json"

        resp = await client.post(url, json=payload)
        resp.raise_for_status()
        data = resp.json()
        return data.get("message", {}).get("content", "")

    async def _call_openai(
        self,
        client: httpx.AsyncClient,
        system: str,
        user: str,
        json_schema: Optional[Dict[str, Any]],
    ) -> str:
        if not self.api_key:
            raise LLMUnavailable("OpenAI requires LLM_API_KEY")
        base = self.base_url or "https://api.openai.com/v1"
        url = f"{base}/chat/completions"
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }
        payload: Dict[str, Any] = {
            "model": self.model or "gpt-4o-mini",
            "messages": [
                {"role": "system", "content": system},
                {"role": "user", "content": user},
            ],
        }
        if json_schema is not None:
            payload["response_format"] = {"type": "json_object"}

        resp = await client.post(url, json=payload, headers=headers)
        resp.raise_for_status()
        data = resp.json()
        choices = data.get("choices", [])
        if not choices:
            raise LLMUnavailable("OpenAI returned no choices")
        return choices[0].get("message", {}).get("content", "")

    async def _call_anthropic(
        self,
        client: httpx.AsyncClient,
        system: str,
        user: str,
        json_schema: Optional[Dict[str, Any]],
    ) -> str:
        if not self.api_key:
            raise LLMUnavailable("Anthropic requires LLM_API_KEY")
        base = self.base_url or "https://api.anthropic.com/v1"
        url = f"{base}/messages"
        headers = {
            "x-api-key": self.api_key,
            "anthropic-version": "2023-06-01",
            "Content-Type": "application/json",
        }
        payload: Dict[str, Any] = {
            "model": self.model or "claude-3-5-haiku-20241022",
            "system": system,
            "messages": [{"role": "user", "content": user}],
            "max_tokens": 1024,
        }
        resp = await client.post(url, json=payload, headers=headers)
        resp.raise_for_status()
        data = resp.json()
        contents = data.get("content", [])
        for block in contents:
            if block.get("type") == "text":
                return block.get("text", "")
        return ""

    async def _call_gemini(
        self,
        client: httpx.AsyncClient,
        system: str,
        user: str,
        json_schema: Optional[Dict[str, Any]],
    ) -> str:
        if not self.api_key:
            raise LLMUnavailable("Gemini requires LLM_API_KEY")
        model = self.model or "gemini-1.5-flash"
        if self.base_url:
            url = f"{self.base_url}/models/{model}:generateContent?key={self.api_key}"
        else:
            url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={self.api_key}"

        payload: Dict[str, Any] = {
            "systemInstruction": {"parts": [{"text": system}]},
            "contents": [{"parts": [{"text": user}]}],
            "generationConfig": {"responseMimeType": "application/json"},
        }
        resp = await client.post(url, json=payload)
        resp.raise_for_status()
        data = resp.json()
        candidates = data.get("candidates", [])
        if not candidates:
            raise LLMUnavailable("Gemini returned no candidates")
        parts = candidates[0].get("content", {}).get("parts", [])
        if not parts:
            raise LLMUnavailable("Gemini returned empty parts")
        return parts[0].get("text", "")
