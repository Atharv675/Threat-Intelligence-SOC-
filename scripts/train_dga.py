#!/usr/bin/env python3
"""Train a DGA (Domain Generation Algorithm) classifier.

Data sources
------------
Benign domains
    Tranco Top-1M list  <https://tranco-list.eu/top-1m.csv.zip>
    We take the first 50,000 entries.

DGA domains
    Johannes Bader's publicly available pre-generated DGA domain lists
    <https://raw.githubusercontent.com/baderj/domain_generation_algorithms/master/generated_domains.txt>
    This repository is a well-known academic resource that contains sample
    domains generated by ~50 real-world DGA families (Conficker, Locky,
    CryptoLocker, etc.).

If either download fails, this script STOPS and prints an error.
No fake data is generated under any circumstances.

Usage
-----
    python scripts/train_dga.py

Output
------
    models/dga_model.joblib   – best scikit-learn classifier
    models/dga_metrics.json   – accuracy, precision, recall, F1, FPR,
                                confusion matrix for both models
"""
from __future__ import annotations

import io
import json
import os
import sys
import zipfile
from pathlib import Path
from typing import List, Optional, Tuple

if sys.stdout and hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    except Exception:
        pass

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
_SCRIPT_DIR = Path(__file__).resolve().parent
_PROJECT_ROOT = _SCRIPT_DIR.parent
_MODELS_DIR = _PROJECT_ROOT / "models"

# Add project root to sys.path so we can import detection.dga_classifier.
sys.path.insert(0, str(_PROJECT_ROOT))


def _ensure_models_dir() -> None:
    _MODELS_DIR.mkdir(parents=True, exist_ok=True)


# ---------------------------------------------------------------------------
# Data acquisition
# ---------------------------------------------------------------------------

TRANCO_URL = "https://tranco-list.eu/top-1m.csv.zip"
DGA_URL = "https://raw.githubusercontent.com/andrewaeva/DGA/master/all_dga.txt"
TRANCO_SAMPLE_SIZE = int(os.environ.get("DGA_TRAIN_SAMPLE_SIZE", "50000"))
DGA_SAMPLE_SIZE = int(os.environ.get("DGA_TRAIN_SAMPLE_SIZE", "50000"))


def _fetch(url: str, label: str) -> bytes:
    """Download *url* and return raw bytes.  Aborts on any failure."""
    import urllib.request

    print(f"[download] {label}")
    print(f"           {url}")
    try:
        with urllib.request.urlopen(url, timeout=120) as resp:
            data = resp.read()
        print(f"           -> {len(data):,} bytes received")
        return data
    except Exception as exc:
        print(
            f"\n[FATAL] Could not download {label}.\n"
            f"        URL : {url}\n"
            f"        Error: {exc}\n"
            "        The script cannot continue without real data. "
            "Check your internet connection and try again.",
            file=sys.stderr,
        )
        sys.exit(1)


def load_tranco(n: int = TRANCO_SAMPLE_SIZE) -> List[str]:
    """Download the Tranco top-1M list and return the first *n* domains."""
    raw = _fetch(TRANCO_URL, "Tranco Top-1M (benign)")
    try:
        with zipfile.ZipFile(io.BytesIO(raw)) as zf:
            # The ZIP contains a single CSV: rank,domain
            csv_name = zf.namelist()[0]
            with zf.open(csv_name) as f:
                lines = f.read().decode("utf-8", errors="ignore").splitlines()
    except Exception as exc:
        print(f"[FATAL] Could not parse Tranco ZIP: {exc}", file=sys.stderr)
        sys.exit(1)

    domains: List[str] = []
    for line in lines:
        if len(domains) >= n:
            break
        parts = line.strip().split(",")
        if len(parts) >= 2:
            domains.append(parts[1].strip().lower())

    print(f"[tranco]  loaded {len(domains):,} benign domains")
    if len(domains) < 1000:
        print("[FATAL] Tranco CSV appears empty or malformed.", file=sys.stderr)
        sys.exit(1)
    return domains


def load_dga(n: int = DGA_SAMPLE_SIZE) -> List[str]:
    """Download pre-generated DGA domains from public DGA dataset via streaming."""
    import urllib.request

    print(f"[download] DGA domain feed")
    print(f"           {DGA_URL}")
    domains: List[str] = []
    try:
        with urllib.request.urlopen(DGA_URL, timeout=60) as resp:
            for raw_line in resp:
                if len(domains) >= n:
                    break
                line = raw_line.decode("utf-8", errors="ignore").strip()
                if not line or line.startswith("#"):
                    continue
                # Line may be just domain or domain + label
                domain = line.split()[0].strip().lower()
                if domain:
                    domains.append(domain)
    except Exception as exc:
        print(f"[FATAL] Could not fetch DGA domain feed: {exc}", file=sys.stderr)
        sys.exit(1)

    print(f"[dga]     loaded {len(domains):,} DGA domains")
    if len(domains) < 100:
        print(
            "[FATAL] DGA domain list appears empty or malformed.\n"
            "        The script cannot continue without real DGA data.",
            file=sys.stderr,
        )
        sys.exit(1)
    return domains


# ---------------------------------------------------------------------------
# Feature extraction
# ---------------------------------------------------------------------------

def build_dataset(
    benign: List[str], dga: List[str]
) -> Tuple["list[list[float]]", "list[int]"]:
    """Convert domain lists to (X, y) for scikit-learn.

    Domains that ``extract_features`` cannot process (IPs, empties, etc.)
    are silently dropped; that is the correct behaviour.
    """
    from detection.dga_classifier import extract_features, _FEATURE_ORDER

    X, y = [], []
    skipped = 0

    for domain, label in [(d, 0) for d in benign] + [(d, 1) for d in dga]:
        feats = extract_features(domain)
        if feats is None:
            skipped += 1
            continue
        X.append([feats[k] for k in _FEATURE_ORDER])
        y.append(label)

    print(f"[dataset] {len(X):,} samples  ({skipped:,} dropped as invalid)")
    pos = sum(y)
    neg = len(y) - pos
    print(f"[dataset] benign={neg:,}  dga={pos:,}")
    return X, y


# ---------------------------------------------------------------------------
# Training & evaluation
# ---------------------------------------------------------------------------

def train_and_evaluate(X_train, y_train, X_test, y_test):
    """Train RandomForest and LogisticRegression; return metrics for both."""
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.linear_model import LogisticRegression
    from sklearn.metrics import (
        accuracy_score,
        confusion_matrix,
        f1_score,
        precision_score,
        recall_score,
    )

    models = {
        "RandomForest": RandomForestClassifier(
            n_estimators=200,
            max_depth=None,
            min_samples_leaf=2,
            n_jobs=-1,
            random_state=42,
        ),
        "LogisticRegression": LogisticRegression(
            max_iter=1000,
            random_state=42,
            solver="lbfgs",
        ),
    }

    results = {}

    for name, clf in models.items():
        print(f"\n[train]   fitting {name} ...")
        clf.fit(X_train, y_train)

        y_pred = clf.predict(X_test)
        acc = accuracy_score(y_test, y_pred)
        prec = precision_score(y_test, y_pred, zero_division=0)
        rec = recall_score(y_test, y_pred, zero_division=0)
        f1 = f1_score(y_test, y_pred, zero_division=0)

        cm = confusion_matrix(y_test, y_pred).tolist()
        # cm = [[TN, FP], [FN, TP]]
        tn, fp, fn, tp = cm[0][0], cm[0][1], cm[1][0], cm[1][1]
        fpr = fp / (fp + tn) if (fp + tn) > 0 else 0.0

        results[name] = {
            "model": clf,
            "metrics": {
                "accuracy": round(acc, 6),
                "precision": round(prec, 6),
                "recall": round(rec, 6),
                "f1": round(f1, 6),
                "false_positive_rate": round(fpr, 6),
                "confusion_matrix": {
                    "TN": tn, "FP": fp, "FN": fn, "TP": tp
                },
            },
        }

        print(f"          accuracy  : {acc:.4f}")
        print(f"          precision : {prec:.4f}")
        print(f"          recall    : {rec:.4f}")
        print(f"          F1        : {f1:.4f}")
        print(f"          FPR       : {fpr:.4f}")
        print(f"          CM        : TN={tn}  FP={fp}  FN={fn}  TP={tp}")

    return results


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    from sklearn.model_selection import train_test_split
    import joblib

    print("=" * 60)
    print("DGA Classifier Training Script")
    print("=" * 60)

    _ensure_models_dir()

    # 1. Download data
    benign_domains = load_tranco()
    dga_domains = load_dga()

    # 2. Build dataset
    X, y = build_dataset(benign_domains, dga_domains)

    # 3. Train/test split BEFORE any tuning (80/20, stratified)
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.20, stratify=y, random_state=42
    )
    print(
        f"\n[split]   train={len(X_train):,}  test={len(X_test):,}  "
        f"(stratified 80/20)"
    )

    # 4. Train and evaluate both models
    results = train_and_evaluate(X_train, y_train, X_test, y_test)

    # 5. Select best model by F1 on the TEST set
    best_name = max(
        results, key=lambda n: results[n]["metrics"]["f1"]
    )
    best_result = results[best_name]
    print(f"\n[select]  best model -> {best_name}  "
          f"(F1={best_result['metrics']['f1']:.4f})")

    # 6. Save model
    model_path = _MODELS_DIR / "dga_model.joblib"
    joblib.dump(best_result["model"], model_path)
    print(f"[save]    model -> {model_path}")

    # 7. Save metrics (all models, clearly separated)
    metrics_payload = {
        "best_model": best_name,
        "feature_order": [
            "label_length", "shannon_entropy", "vowel_ratio",
            "digit_ratio", "longest_consonant_run", "digit_count",
            "bigram_score",
        ],
        "data_sources": {
            "benign": TRANCO_URL,
            "dga": DGA_URL,
        },
        "train_test_split": "80/20 stratified",
        "models": {
            name: res["metrics"]
            for name, res in results.items()
        },
    }

    metrics_path = _MODELS_DIR / "dga_metrics.json"
    with open(metrics_path, "w", encoding="utf-8") as f:
        json.dump(metrics_payload, f, indent=2)
    print(f"[save]    metrics -> {metrics_path}")

    print("\n" + "=" * 60)
    print("Training complete.")
    print("=" * 60)

    # 8. Print final summary for the user
    m = best_result["metrics"]
    cm = m["confusion_matrix"]
    print(f"\n  Best model  : {best_name}")
    print(f"  Accuracy    : {m['accuracy']}")
    print(f"  Precision   : {m['precision']}")
    print(f"  Recall      : {m['recall']}")
    print(f"  F1          : {m['f1']}")
    print(f"  FPR         : {m['false_positive_rate']}  "
          f"({cm['FP']} false positives out of {cm['FP'] + cm['TN']} benign test samples)")
    print(f"  Confusion   : TN={cm['TN']}  FP={cm['FP']}  "
          f"FN={cm['FN']}  TP={cm['TP']}")


if __name__ == "__main__":
    main()
